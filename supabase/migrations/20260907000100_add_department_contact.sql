-- 소속에 연락처와 이메일을 둔다.
--
-- 지사에 무언가를 알리거나 물어야 할 때(사은품 발주 확인, 민원 처리 독촉)
-- 지금은 어디로 연락해야 하는지가 시스템 밖에 있다. 소속 행에 붙여 두면
-- 소속을 고르는 화면 어디서든 같은 값을 본다.
--
-- 둘 다 비워 둘 수 있다. '관리자'·'담당자'·'이외지역'은 사람이 속하는 조직이
-- 아니라 역할 전용 자리라 연락처가 있을 수 없고, 이미 있는 지사도 나중에
-- 채운다. 필수로 걸면 소속을 만들 때마다 없는 값을 지어내게 된다.
--
-- 소속을 읽는 열아홉 곳 모두 열 이름을 집어 읽으므로(SELECT * 없음), 열이
-- 늘어도 그쪽은 모른다. 소속 관리 화면과 그 API만 이 열을 안다.

ALTER TABLE public.departments
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS email text;
