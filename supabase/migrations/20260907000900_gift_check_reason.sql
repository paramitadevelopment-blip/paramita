-- 같은 주문번호로 다시 신청할 때의 사유.
--
-- 한 주문번호로 여러 상품을 가입하거나, 사은품을 추가로 달라는 일이 있다. 그래서
-- 같은 주문번호의 두 번째 신청을 막지는 않되, **왜 또 보내는지**를 적게 하고
-- 관리자가 확인한 뒤에 담당자에게 간다(status = pending_check). 확인이 끝나면
-- 사유는 그 건에 남는다 — 나중에 "이 고객에게 왜 두 번 갔나"를 되짚는 근거다.
--
-- 주문번호가 없거나 배포 기록에 없는 건은 이제 앞단에서 거절한다. 관리자 확인
-- 대기는 재신청 한 가지 뜻이다.

