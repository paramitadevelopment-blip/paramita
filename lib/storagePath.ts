/**
 * 저장소 경로 규칙.
 *
 * 저장소 앞에 캐시가 있어 **같은 경로를 덮어쓰면 몇 초 동안 옛 파일이 온다**
 * (직접 재어 보니 3초까지는 옛것, 10초 뒤에야 새것). 그래서 내용이 바뀌는
 * 파일은 덮어쓰지 않고 새 경로에 쓴 뒤 DB가 그 경로를 가리키게 한다.
 * 새 경로는 캐시가 본 적이 없어 첫 요청부터 새 내용이 온다.
 */

/**
 * 배포로 다시 만든 원본이 갈 자리.
 *
 * 업로드 경로의 확장자 앞에 `_deployed_<시각>`을 끼운다. 같은 원본을 다시
 * 만들어도 시각이 달라 경로가 겹치지 않는다. 확장자가 없으면 그냥 뒤에 붙인다.
 * 폴더 이름에 든 점(`a.b/c`)은 확장자로 안 본다.
 */
export function deployedStoragePath(uploadedPath: string, at: number = Date.now()): string {
  return uploadedPath.replace(/(\.[^./]+)?$/, (ext) => `_deployed_${at}${ext}`);
}
